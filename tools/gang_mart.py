#!/usr/bin/env python3
"""Gangster Outbreak: writes data/scripts/gang_mart.inc, the stock of every Kanto / Sevii mart (vending
machines) for each gang rank. A rank is one Gym Badge; better goods replace the old ones instead of piling up.

Usage: python3 tools/gang_mart.py
"""
import os, re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

X_ITEMS = 'X_ATTACK X_DEFENSE X_SPEED X_SP_ATK X_SP_DEF X_ACCURACY DIRE_HIT GUARD_SPEC'
STONES = 'FIRE_STONE WATER_STONE THUNDER_STONE LEAF_STONE MOON_STONE SUN_STONE SHINY_STONE DUSK_STONE DAWN_STONE ICE_STONE'
EVO_ITEMS = 'LINKING_CORD METAL_COAT KINGS_ROCK UPGRADE DUBIOUS_DISC DRAGON_SCALE PROTECTOR ELECTIRIZER MAGMARIZER REAPER_CLOTH'
HELD_1 = 'LEFTOVERS EXPERT_BELT ROCKY_HELMET'
HELD_2 = HELD_1 + ' LIFE_ORB FOCUS_SASH ASSAULT_VEST EVIOLITE'
VITAMINS = 'HP_UP PROTEIN IRON CALCIUM ZINC CARBOS'
STATUS = 'ANTIDOTE PARALYZE_HEAL AWAKENING BURN_HEAL ICE_HEAL'

# badges -> (rank name, stock)
RANKS = [
    ('RECRUIT', 'POKE_BALL POTION ' + STATUS + ' REPEL'),
    ('PROSPECT', 'POKE_BALL GREAT_BALL POTION SUPER_POTION ' + STATUS + ' REPEL X_ATTACK X_DEFENSE'),
    ('RUNNER', 'POKE_BALL GREAT_BALL NET_BALL NEST_BALL SUPER_POTION FULL_HEAL REVIVE SUPER_REPEL ' + X_ITEMS),
    ('SOLDIER', 'GREAT_BALL ULTRA_BALL NET_BALL NEST_BALL DUSK_BALL QUICK_BALL SUPER_POTION HYPER_POTION FULL_HEAL '
                'REVIVE SUPER_REPEL ' + X_ITEMS + ' FIRE_STONE WATER_STONE THUNDER_STONE LEAF_STONE MOON_STONE'),
    ('ENFORCER', 'GREAT_BALL ULTRA_BALL NET_BALL NEST_BALL DUSK_BALL QUICK_BALL TIMER_BALL REPEAT_BALL HYPER_POTION '
                 'FULL_HEAL REVIVE ETHER MAX_REPEL ' + X_ITEMS + ' ' + STONES + ' ' + EVO_ITEMS),
    ('HITMAN', 'ULTRA_BALL QUICK_BALL DUSK_BALL TIMER_BALL REPEAT_BALL NET_BALL HYPER_POTION MAX_POTION FULL_HEAL '
               'REVIVE ETHER ELIXIR MAX_REPEL ' + X_ITEMS + ' ' + STONES + ' ' + EVO_ITEMS + ' ' + HELD_1),
    ('CAPO', 'ULTRA_BALL QUICK_BALL DUSK_BALL TIMER_BALL REPEAT_BALL LUXURY_BALL MAX_POTION FULL_RESTORE FULL_HEAL '
             'REVIVE MAX_REVIVE MAX_ETHER ELIXIR MAX_REPEL ' + X_ITEMS + ' ' + STONES + ' ' + EVO_ITEMS + ' ' + HELD_2),
    ('UNDERBOSS', 'ULTRA_BALL QUICK_BALL DUSK_BALL TIMER_BALL REPEAT_BALL LUXURY_BALL MAX_POTION FULL_RESTORE '
                  'FULL_HEAL MAX_REVIVE MAX_ETHER MAX_ELIXIR MAX_REPEL ' + X_ITEMS + ' ' + STONES + ' ' + EVO_ITEMS + ' '
                  + HELD_2 + ' CHOICE_BAND CHOICE_SPECS CHOICE_SCARF ' + VITAMINS + ' PP_UP'),
    ('KINGPIN', 'ULTRA_BALL QUICK_BALL DUSK_BALL TIMER_BALL REPEAT_BALL LUXURY_BALL FULL_RESTORE MAX_POTION '
                'FULL_HEAL MAX_REVIVE MAX_ELIXIR MAX_REPEL ' + X_ITEMS + ' ' + STONES + ' ' + EVO_ITEMS + ' ' + HELD_2
                + ' CHOICE_BAND CHOICE_SPECS CHOICE_SCARF ' + VITAMINS + ' PP_UP PP_MAX RARE_CANDY ABILITY_CAPSULE BOTTLE_CAP'),
]


def main():
    items = set(re.findall(r'\b(ITEM_\w+)\b', open(os.path.join(ROOT, 'include/constants/items.h')).read()))
    out = ['@ Gangster Outbreak: one shared stock for all Kanto and Sevii marts (vending machines), one list per gang',
           '@ rank (= Gym Badges). Generated by tools/gang_mart.py - edit the lists there.', '',
           'EventScript_GangMart::', '\tspecial GangItems_CountBadges']
    for n in range(len(RANKS)):
        out.append('\tgoto_if_eq VAR_RESULT, %d, EventScript_GangMart%d' % (n, n))
    out += ['\tgoto EventScript_GangMart%d' % (len(RANKS) - 1), '']
    for n, (rank, stock) in enumerate(RANKS):
        names = stock.split()
        assert len(names) == len(set(names)), '%s: duplicate items' % rank
        for name in names:
            assert 'ITEM_' + name in items, 'unknown item ' + name
        out += ['EventScript_GangMart%d::' % n, '\tpokemart GangMart_Items%d' % n, '\treturn', '',
                '\t.align 2', 'GangMart_Items%d: @ %s, %d items' % (n, rank, len(names))]
        out += ['\t.2byte ITEM_%s' % name for name in names]
        out += ['\tpokemartlistend', '']
    open(os.path.join(ROOT, 'data/scripts/gang_mart.inc'), 'w').write('\n'.join(out))
    print('\n'.join('%-10s %2d items' % (r, len(s.split())) for r, s in RANKS))


if __name__ == '__main__':
    main()
